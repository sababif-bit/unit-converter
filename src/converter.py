def kilometer_to_meter(kilometers):
    """
    Convert kilometers to meters.

    Parameters:
    kilometers (float): The distance in kilometers.

    Returns:
    float: The distance in meters.
    """
    return kilometers * 1000

def kilogram_to_gram(kilograms):
    """
    Convert kilograms to grams.

    Parameters:
    kilograms (float): The weight in kilograms.

    Returns:
    float: The weight in grams.
    """
    return kilograms * 1000

def meter_to_kilometer(meters):
    """
    Convert meters to kilometers.

    Parameters:
    meters (float): The distance in meters.

    Returns:
    float: The distance in kilometers.
    """
    return meters / 1000

def gram_to_kilogram(grams):
    """
    Convert grams to kilograms.

    Parameters:
    grams (float): The weight in grams.

    Returns:
    float: The weight in kilograms.
    """
    return grams / 1000

def celsius_to_fahrenheit(celsius):
    """
    Convert Celsius to Fahrenheit.

    Parameters:
    celsius (float): The temperature in Celsius.

    Returns:
    float: The temperature in Fahrenheit.
    """
    return (celsius * 9/5) + 32

def fahrenheit_to_celsius(fahrenheit):
    """
    Convert Fahrenheit to Celsius.

    Parameters:
    fahrenheit (float): The temperature in Fahrenheit.

    Returns:
    float: The temperature in Celsius.
    """
    return (fahrenheit - 32) * 5/9